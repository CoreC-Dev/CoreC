package executor

import (
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/CoreC-Dev/CoreC/hub/route"
)

// configBackupMax is the maximum number of backup files retained in the
// backup directory. When a new backup is written and the set exceeds this
// count, the oldest backups are deleted (newest N kept).
const configBackupMax = 10

// backupDirName is the subdirectory (next to the active config file) that
// holds the backup files.
const backupDirName = "backups"

// backupExt is the file extension of generated backup files.
const backupExt = ".yaml"

// backupNamePattern strictly matches backup file names generated by this
// package: <unix-nano>.yaml. Anchored on both ends and accepting digits only,
// it rejects path separators, traversal fragments ("..", "../x"), absolute
// paths, and suffixed names ("1.yaml.bak") before any filesystem path is
// ever joined, so a caller-supplied name can never escape the backup
// directory.
var backupNamePattern = regexp.MustCompile(`^\d{1,25}\.yaml$`)

// backupDir returns the directory holding config backups, derived from the
// active config path: <dir(configPath)>/backups. Returns route.ErrNoConfigPath
// when the executor was started without a persisted config file (empty-config
// startup) — backups are a persisted-file feature, so callers surface a clear
// error instead of guessing a location.
func backupDir() (string, error) {
	mux.Lock()
	p := configPath
	mux.Unlock()

	if p == "" {
		return "", route.ErrNoConfigPath
	}
	return filepath.Join(filepath.Dir(p), backupDirName), nil
}

// parseBackupName validates a backup file name and returns the unix-nano
// timestamp encoded in it. ok is false for anything that is not a strict
// generated backup name.
func parseBackupName(name string) (stamp int64, ok bool) {
	if !backupNamePattern.MatchString(name) {
		return 0, false
	}
	n, err := strconv.ParseInt(strings.TrimSuffix(name, backupExt), 10, 64)
	if err != nil || n <= 0 {
		return 0, false
	}
	return n, true
}

// backupFileName returns the generated file name for a unix-nano stamp.
func backupFileName(stamp int64) string {
	return strconv.FormatInt(stamp, 10) + backupExt
}

// saveConfigBackup writes data as a new timestamped backup file (0o600) and
// prunes the set down to configBackupMax entries. Returns the backup's file
// name.
func saveConfigBackup(data []byte) (string, error) {
	dir, err := backupDir()
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", fmt.Errorf("failed to create config backup directory: %w", err)
	}

	name := backupFileName(time.Now().UnixNano())
	target := filepath.Join(dir, name)
	// 0o600: owner read/write only, same rationale as the active config file
	// in Reload — backups contain the API secret and driver/transport
	// credentials, so world/group-readable files would leak them to other
	// users on the host.
	if err := os.WriteFile(target, data, 0o600); err != nil {
		return "", fmt.Errorf("failed to write config backup %s: %w", name, err)
	}
	// os.WriteFile only applies perm on file creation and the umask may
	// clear owner bits; chmod explicitly (mirrors the persist path in
	// Reload) so the backup is never more open than 0o600. Non-fatal on
	// failure: the file was created with at most 0o600 already.
	if err := os.Chmod(target, 0o600); err != nil {
		slog.Warn("config backup created but failed to tighten file permissions",
			"path", target, "error", err)
	}
	slog.Info("config backup created", "name", name, "size", len(data))

	pruneConfigBackups(dir)
	return name, nil
}

// pruneConfigBackups removes the oldest backups so that at most
// configBackupMax files remain in dir. Best effort: deletion errors are
// logged, never returned — pruning must not fail an otherwise successful
// reload. Non-backup files in the directory are left untouched.
func pruneConfigBackups(dir string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		slog.Warn("config backup prune skipped: cannot list backup directory",
			"dir", dir, "error", err)
		return
	}
	var stamps []int64
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		if stamp, ok := parseBackupName(e.Name()); ok {
			stamps = append(stamps, stamp)
		}
	}
	if len(stamps) <= configBackupMax {
		return
	}
	sort.Slice(stamps, func(i, j int) bool { return stamps[i] < stamps[j] })
	for _, stamp := range stamps[:len(stamps)-configBackupMax] {
		target := filepath.Join(dir, backupFileName(stamp))
		if err := os.Remove(target); err != nil && !os.IsNotExist(err) {
			slog.Warn("config backup prune failed to remove old backup",
				"file", target, "error", err)
		}
	}
}

// snapshotExistingConfig copies the current on-disk config file at path into
// the backup set. Called by Reload immediately before a new payload
// overwrites the file, so every successful dashboard-driven change is
// preceded by a point-in-time snapshot of the replaced content (the
// pre-change state an operator rolls back to).
//
// A missing file is a silent no-op (first persist — nothing to back up);
// any other failure only logs a warning: a failed snapshot must never block
// an otherwise valid reload (availability first).
func snapshotExistingConfig(path string) {
	info, err := os.Stat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return
		}
		slog.Warn("config backup skipped: cannot access active config file",
			"path", path, "error", err)
		return
	}
	if !info.Mode().IsRegular() {
		slog.Warn("config backup skipped: active config path is not a regular file",
			"path", path)
		return
	}
	data, err := os.ReadFile(path)
	if err != nil {
		slog.Warn("config backup skipped: cannot read active config file",
			"path", path, "error", err)
		return
	}
	if _, err := saveConfigBackup(data); err != nil {
		slog.Warn("config backup failed; reload proceeds without a new snapshot",
			"error", err)
	}
}

// ListConfigBackups returns metadata for the retained config backups, newest
// first. An empty list is returned when no backup has been taken yet.
// Returns route.ErrNoConfigPath when no config file path is set.
func ListConfigBackups() ([]route.ConfigBackupInfo, error) {
	dir, err := backupDir()
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return []route.ConfigBackupInfo{}, nil
		}
		return nil, fmt.Errorf("failed to list config backups: %w", err)
	}

	backups := make([]route.ConfigBackupInfo, 0, len(entries))
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		stamp, ok := parseBackupName(e.Name())
		if !ok {
			continue // not a generated backup file — ignore
		}
		info, err := e.Info()
		if err != nil {
			slog.Warn("config backup listing skipped unreadable entry",
				"name", e.Name(), "error", err)
			continue
		}
		backups = append(backups, route.ConfigBackupInfo{
			Name:      e.Name(),
			Timestamp: time.Unix(0, stamp).UTC(),
			Size:      info.Size(),
		})
	}
	sort.Slice(backups, func(i, j int) bool {
		return backups[i].Timestamp.After(backups[j].Timestamp)
	})
	return backups, nil
}

// GetConfigBackup returns the YAML content of the named backup. name must be
// an exact backup file name ("<unix-nano>.yaml") as listed by
// ListConfigBackups; arbitrary names, paths, and traversal fragments are
// rejected with route.ErrInvalidBackupName before any path is joined, so
// this can never read outside the backup directory. Unknown-but-well-formed
// names yield route.ErrBackupNotFound.
func GetConfigBackup(name string) (string, error) {
	if _, ok := parseBackupName(name); !ok {
		return "", fmt.Errorf("%w: %q", route.ErrInvalidBackupName, name)
	}
	dir, err := backupDir()
	if err != nil {
		return "", err
	}
	data, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		if os.IsNotExist(err) {
			return "", fmt.Errorf("%w: %s", route.ErrBackupNotFound, name)
		}
		return "", fmt.Errorf("failed to read config backup %s: %w", name, err)
	}
	return string(data), nil
}

// CreateConfigBackup takes a manual snapshot of the current on-disk config
// file and returns the new backup's file name. Returns route.ErrNoConfigPath
// when no config path is set and route.ErrConfigFileMissing when the file
// does not exist on disk yet (there is nothing to snapshot).
func CreateConfigBackup() (string, error) {
	mux.Lock()
	p := configPath
	mux.Unlock()

	if p == "" {
		return "", route.ErrNoConfigPath
	}
	info, err := os.Stat(p)
	if err != nil {
		if os.IsNotExist(err) {
			return "", route.ErrConfigFileMissing
		}
		return "", fmt.Errorf("failed to access active config file: %w", err)
	}
	if !info.Mode().IsRegular() {
		return "", fmt.Errorf("active config path is not a regular file: %s", p)
	}
	data, err := os.ReadFile(p)
	if err != nil {
		return "", fmt.Errorf("failed to read active config file: %w", err)
	}
	return saveConfigBackup(data)
}

// RestoreConfigBackup restores the named backup through the full reload
// chain: the backup content is handed to Reload as an inline payload, so it
// goes through the exact same parse → validate → ApplyConfig → persist
// pipeline as a dashboard PUT /configs — a backup is never blindly copied
// over the active file.
//
// The backup content is pre-validated first so a backup that no longer
// passes validation fails with route.ErrBackupInvalid before anything is
// applied, leaving the current configuration and on-disk file untouched.
// On success the restored content is persisted to the active config file
// (and, like every payload reload, the replaced on-disk state is snapshotted
// first — so a restore can itself be rolled back).
func RestoreConfigBackup(name string) error {
	content, err := GetConfigBackup(name)
	if err != nil {
		return err
	}
	if _, verr := Validate(content); verr != nil {
		return fmt.Errorf("%w: %w", route.ErrBackupInvalid, verr)
	}
	return Reload("", content)
}
